-- ----------------------------------------------------------------------------
-- B) Écriture admin — SECURITY DEFINER.  >>> À EXÉCUTER À LA MAIN si MCP timeout <<<
-- ----------------------------------------------------------------------------
-- Ajoute un moment (clé dérivée du libellé, placée en fin de liste).
CREATE OR REPLACE FUNCTION public.admin_add_moment(p_label text)
 RETURNS json LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public'
AS $function$
declare
  v_label text := nullif(btrim(p_label),'');
  v_key text;
  v_ordre int;
  v_id bigint;
begin
  if not public.is_admin() then raise exception 'Réservé à l''administrateur.'; end if;
  if v_label is null then raise exception 'Libellé vide.'; end if;
  v_key := lower(regexp_replace(regexp_replace(public.unaccent(v_label),'[^a-zA-Z0-9]+','_','g'),'(^_+|_+$)','','g'));
  if v_key = '' then v_key := 'moment'; end if;
  -- clé déjà prise → on renvoie le moment existant (réactivé)
  if exists (select 1 from public.moments where key = v_key) then
    update public.moments set actif = true, label = v_label where key = v_key;
    select id into v_id from public.moments where key = v_key;
    return (select row_to_json(m) from (select id, key, label, ordre, actif from public.moments where id = v_id) m);
  end if;
  select coalesce(max(ordre), -1) + 1 into v_ordre from public.moments;
  insert into public.moments (key, label, ordre) values (v_key, v_label, v_ordre) returning id into v_id;
  return (select row_to_json(m) from (select id, key, label, ordre, actif from public.moments where id = v_id) m);
end $function$;

-- Supprime un moment (ne touche pas aux CSV existants des invocations).
CREATE OR REPLACE FUNCTION public.admin_delete_moment(p_id bigint)
 RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public'
AS $function$
begin
  if not public.is_admin() then raise exception 'Réservé à l''administrateur.'; end if;
  delete from public.moments where id = p_id;
end $function$;
