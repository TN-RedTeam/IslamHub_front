CREATE OR REPLACE FUNCTION public.admin_save_parole(p jsonb)
 RETURNS bigint LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public'
AS $function$
declare
  v_id bigint := nullif(p->>'id','')::bigint;
  v_savant_id bigint := nullif(p->>'savant_id','')::bigint;
  v_rapporteur bigint := nullif(p->>'rapporteur_savant_id','')::bigint;
  v_commente bigint := nullif(p->>'commente_parole_id','')::bigint;
  v_livre text := nullif(btrim(p->>'commente_livre'),'');
  v_savant_nom text; v_slug text; v_sslug text; im jsonb;
begin
  if not public.is_admin() then raise exception 'Écriture réservée à l''administrateur.'; end if;

  if (p->'new_savant') is not null and nullif(btrim(p->'new_savant'->>'nom'),'') is not null then
    v_savant_nom := btrim(p->'new_savant'->>'nom');
    v_sslug := lower(regexp_replace(regexp_replace(public.unaccent(v_savant_nom),'[^a-zA-Z0-9]+','-','g'),'(^-+|-+$)','','g'));
    if v_sslug='' or exists (select 1 from public.savants where slug=v_sslug) then v_sslug := coalesce(nullif(v_sslug,''),'savant')||'-'||floor(random()*100000)::text; end if;
    insert into public.savants (nom, slug) values (v_savant_nom, v_sslug)
    on conflict (nom) do update set nom=excluded.nom returning id, nom into v_savant_id, v_savant_nom;
  elsif v_savant_id is not null then
    select nom into v_savant_nom from public.savants where id=v_savant_id;
  end if;

  if v_id is null then
    v_slug := lower(regexp_replace(regexp_replace(public.unaccent(coalesce(p->>'sujet','parole')),'[^a-zA-Z0-9]+','-','g'),'(^-+|-+$)','','g'));
    if v_slug='' then v_slug:='parole'; end if;
    if exists (select 1 from public.paroles where slug=v_slug) then v_slug := v_slug||'-'||floor(random()*100000)::text; end if;
    insert into public.paroles (sujet, rubrique, intro, savant, savant_id, texte_arabe, texte_francais, "phonétique", explication, tag, ecole, source_livre, page, slug, rapporteur_savant_id, commente_parole_id, commente_livre)
    values (nullif(btrim(p->>'sujet'),''), nullif(btrim(p->>'rubrique'),''), nullif(btrim(p->>'intro'),''), v_savant_nom, v_savant_id, btrim(p->>'texte_arabe'), nullif(p->>'texte_francais',''),
            nullif(p->>'phonetique',''), nullif(p->>'explication',''), nullif(p->>'tag',''), nullif(p->>'ecole',''),
            nullif(p->>'source_livre',''), nullif(p->>'page',''), v_slug, v_rapporteur, v_commente, v_livre)
    returning id into v_id;
  else
    update public.paroles set sujet=nullif(btrim(p->>'sujet'),''), rubrique=nullif(btrim(p->>'rubrique'),''), intro=nullif(btrim(p->>'intro'),''), savant=v_savant_nom, savant_id=v_savant_id,
      texte_arabe=btrim(p->>'texte_arabe'), texte_francais=nullif(p->>'texte_francais',''),
      "phonétique"=nullif(p->>'phonetique',''), explication=nullif(p->>'explication',''),
      tag=nullif(p->>'tag',''), ecole=nullif(p->>'ecole',''), source_livre=nullif(p->>'source_livre',''), page=nullif(p->>'page',''),
      rapporteur_savant_id=v_rapporteur, commente_parole_id=v_commente, commente_livre=v_livre
    where id=v_id;
  end if;

  delete from public.parole_images where parole_id=v_id;
  for im in select * from jsonb_array_elements(coalesce(p->'images','[]'::jsonb)) loop
    if nullif(btrim(im->>'image_url'),'') is not null then
      insert into public.parole_images (parole_id, image_url, alt, legende, source_livre, source_livre_ar, ordre)
      values (v_id, btrim(im->>'image_url'), coalesce(nullif(btrim(im->>'alt'),''), 'Scan du livre'),
              nullif(im->>'legende',''), nullif(im->>'source_livre',''), nullif(btrim(im->>'source_livre_ar'),''), coalesce(nullif(im->>'ordre','')::int, 0));
    end if;
  end loop;

  if p ? 'segments' then
    delete from public.parole_segments where parole_id = v_id;
    insert into public.parole_segments (parole_id, ordre, intro, texte_arabe, phonetique, texte_francais, explication)
    select v_id, (e.ord)::int,
           nullif(btrim(e.val->>'intro'),''), nullif(btrim(e.val->>'texte_arabe'),''),
           nullif(btrim(e.val->>'phonetique'),''), nullif(btrim(e.val->>'texte_francais'),''),
           nullif(btrim(e.val->>'explication'),'')
    from jsonb_array_elements(coalesce(p->'segments','[]'::jsonb)) with ordinality as e(val, ord)
    where coalesce(btrim(e.val->>'texte_arabe'),'') <> '' or coalesce(btrim(e.val->>'texte_francais'),'') <> ''
          or coalesce(btrim(e.val->>'intro'),'') <> '' or coalesce(btrim(e.val->>'explication'),'') <> '';
  end if;

  delete from public.parole_themes where parole_id=v_id;
  insert into public.parole_themes (parole_id, theme_slug)
  select v_id, tt.theme_slug from unnest(string_to_array(coalesce(p->>'tag',''),',')) raw(tok)
  join public.theme_tags tt on regexp_replace(lower(btrim(tt.tag_token)),'\s+',' ','g')=regexp_replace(lower(btrim(raw.tok)),'\s+',' ','g')
  where btrim(raw.tok)<>'' on conflict do nothing;

  return v_id;
end $function$;

-- ----------------------------------------------------------------------------
-- D) Recherche admin : rendre les blocs de PAROLE trouvables (ajout 'parole').
--    >>> À EXÉCUTER <<< (identique à 11w + 'parole' dans la branche blocs)
-- ----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.admin_search_occurrences(q text, p_limit integer DEFAULT 120)
 RETURNS json LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public', 'pg_temp'
AS $function$
declare
  pat text;
begin
  if not public.is_admin() then raise exception 'Réservé à l''administrateur.'; end if;
  if nullif(btrim(coalesce(q,'')),'') is null then return '[]'::json; end if;
  pat := '%'||public.unaccent(lower(btrim(q)))||'%';
  return (
    with hits as (
      select 'Hadith' as kind, h.id::text as ref, h.sujet as label,
             public.admin_snip(concat_ws(' | ', h.sujet, h.rapporteur, h.narrateur, h.texte_francais, h.explication, h.texte_arabe), q) as extrait,
             '/admin/hadiths/'||h.id as path
      from public.hadiths h
      where public.unaccent(lower(concat_ws(' ', h.sujet, h.rapporteur, h.narrateur, h.juge_par, h.texte_francais, h.explication, h.tag))) like pat
         or public.ar_match(h.texte_arabe, q)
      union all
      select 'Parole', p.id::text, p.sujet,
             public.admin_snip(concat_ws(' | ', p.sujet, p.savant, p.texte_francais, p.explication, p.source_livre, p.texte_arabe), q),
             '/admin/paroles/'||p.id
      from public.paroles p
      where public.unaccent(lower(concat_ws(' ', p.sujet, p.savant, p.texte_francais, p.explication, p.source_livre, p.intro, p.tag))) like pat
         or public.ar_match(p.texte_arabe, q)
      union all
      select 'Coran', c.id::text, c.sujet,
             public.admin_snip(concat_ws(' | ', c.sujet, c.sourate, c.texte_francais, c.explication, c.texte_arabe), q),
             '/admin/coran/'||c.id
      from public.coran c
      where public.unaccent(lower(concat_ws(' ', c.sujet, c.sourate, c.texte_francais, c.explication, c.tag))) like pat
         or public.ar_match(c.texte_arabe, q)
      union all
      select 'Invocation', i.id::text, i.sujet,
             public.admin_snip(concat_ws(' | ', i.sujet, i.texte_francais, i.commentaire, i.explication, i.texte_arabe), q),
             '/admin/invocations/'||i.id
      from public.invocations i
      where public.unaccent(lower(concat_ws(' ', i.sujet, i.texte_francais, i.commentaire, i.explication, i.tag))) like pat
         or public.ar_match(i.texte_arabe, q)
      union all
      select 'Équivoque', v.id::text, v.theme,
             public.admin_snip(concat_ws(' | ', v.theme, v.rapporteur, v.recueil, v.verset_traduction, v.sens_juste, v.objection, v.reponse, v.verset_arabe), q),
             '/admin/equivoques/'||v.id
      from public.versets_equivoques v
      where public.unaccent(lower(concat_ws(' ', v.theme, v.sourate, v.rapporteur, v.recueil, v.verset_traduction, v.sens_juste, v.objection, v.reponse))) like pat
         or public.ar_match(v.verset_arabe, q)
      union all
      select 'Dossier', d.id::text, d.h1,
             public.admin_snip(concat_ws(' | ', d.h1, d.croyance_texte, d.objection_texte, d.reponse_texte), q),
             '/admin/dossiers/'||d.id
      from public.dossiers d
      where public.unaccent(lower(concat_ws(' ', d.h1, d.meta_title, d.meta_description, d.croyance_texte, d.objection_texte, d.reponse_texte))) like pat
         or public.ar_match(concat_ws(' ', d.croyance_texte, d.objection_texte, d.reponse_texte), q)
      union all
      select 'Exposé', e.slug, e.titre,
             public.admin_snip(concat_ws(' | ', e.titre, e.contenu_md, e.verset_traduction, e.verset_arabe), q),
             '/admin/exposes/'||e.slug
      from public.exposes e
      where public.unaccent(lower(concat_ws(' ', e.titre, e.contenu_md, e.verset_traduction, e.verset_ref))) like pat
         or public.ar_match(concat_ws(' ', e.verset_arabe, e.contenu_md), q)
      union all
      select 'Récit', r.id::text, r.titre,
             public.admin_snip(concat_ws(' | ', r.titre, r.contenu_md), q),
             '/admin/recits/'||r.id
      from public.recits r
      where public.unaccent(lower(concat_ws(' ', r.titre, r.contenu_md))) like pat
         or public.ar_match(r.contenu_md, q)
      union all
      select 'Fiqh', f.id::text, coalesce(nullif(f.sujet,''), f.chapitre),
             public.admin_snip(concat_ws(' | ', f.chapitre, f.sujet, f.texte, f.source, f.texte_arabe), q),
             '/admin/fiqh/'||f.id
      from public.fiqh f
      where public.unaccent(lower(concat_ws(' ', f.chapitre, f.sujet, f.texte, f.source, f.tag))) like pat
         or public.ar_match(concat_ws(' ', f.texte_arabe, f.texte), q)
      union all
      select 'Femme', fm.id::text, fm.chapitre,
             public.admin_snip(concat_ws(' | ', fm.chapitre, fm.matn, fm.commentaire, fm.source, fm.texte_arabe), q),
             '/admin/femmes/'||fm.id
      from public.femmes fm
      where public.unaccent(lower(concat_ws(' ', fm.chapitre, fm.matn, fm.commentaire, fm.source))) like pat
         or public.ar_match(concat_ws(' ', fm.texte_arabe, fm.matn, fm.commentaire), q)
      union all
      select 'Savant', s.id::text, s.nom,
             public.admin_snip(concat_ws(' | ', s.nom, s.resume, s.biographie, s.nom_arabe), q),
             '/admin/savants/'||s.id
      from public.savants s
      where public.unaccent(lower(concat_ws(' ', s.nom, s.nom_arabe, s.resume, s.biographie, s.naissance, s.deces))) like pat
         or public.ar_match(concat_ws(' ', s.nom_arabe, s.resume, s.biographie), q)
      union all
      select 'Bloc d''article', b.parent_id,
             'Bloc '||b.type||' — '||b.parent_type,
             public.admin_snip(concat_ws(' | ', b.texte_md, b.commentaire_md), q),
             case b.parent_type
               when 'equivoque' then '/admin/equivoques/'||b.parent_id
               when 'expose' then '/admin/exposes/'||b.parent_id
               when 'recit' then '/admin/recits/'||b.parent_id
               when 'dossier' then '/admin/dossiers/'||b.parent_id
               when 'hadith' then '/admin/hadiths/'||b.parent_id
               when 'parole' then '/admin/paroles/'||b.parent_id end
      from public.contenu_blocs b
      where b.type in ('texte','commentaire')
        and b.parent_type in ('equivoque','expose','recit','dossier','hadith','parole')
        and (public.unaccent(lower(concat_ws(' ', b.texte_md, b.commentaire_md))) like pat
             or public.ar_match(concat_ws(' ', b.texte_md, b.commentaire_md), q))
    )
    select coalesce(json_agg(row_to_json(x)), '[]'::json)
    from (select * from hits where path is not null order by kind, label limit p_limit) x
  );
end $function$;
