-- ============================================================================
-- Rubrique « Questions fréquentes » — sous-partie 1 : schéma (ADD ONLY)
-- ============================================================================
-- Réutilise l'infra existante : le développement sourcé passe par
-- contenu_blocs (parent_type='question', get_blocs/admin_save_blocs sont déjà
-- génériques), les thèmes par la table themes. On n'ajoute que 3 tables légères.
-- Locale-aware dès le départ (cohérence Phase 15). RLS durcie comme le reste
-- (publié uniquement pour le public ; admin via is_admin()).
-- NON DESTRUCTIF : aucune table existante n'est modifiée.
-- ============================================================================

create extension if not exists pgcrypto;

-- 1) La question elle-même
create table if not exists public.questions (
  id                bigint generated by default as identity primary key,
  question          text not null,                       -- libellé exact (= <h1> + <title>)
  slug              text not null,                        -- /questions/<slug>
  reponse_courte    text,                                 -- encart + meta description
  variantes         text[] not null default '{}',         -- synonymes (SEO + recherche interne)
  publiee           boolean not null default false,       -- ne publier que les questions rédigées
  ordre             integer not null default 0,
  locale            text not null default 'fr' check (locale in ('fr','en','ar')),
  translation_group uuid not null default gen_random_uuid(),
  created_at        timestamptz not null default now()
);
create unique index if not exists questions_slug_key on public.questions(slug);
create index if not exists questions_locale_idx on public.questions(locale);
create index if not exists questions_tg_idx on public.questions(translation_group);
alter table public.questions drop constraint if exists questions_tg_locale_uq;
alter table public.questions add constraint questions_tg_locale_uq unique (translation_group, locale);

-- 2) Liaison aux thèmes (calquée sur hadith_themes/coran_themes)
create table if not exists public.question_themes (
  question_id bigint not null references public.questions(id) on delete cascade,
  theme_slug  text   not null references public.themes(slug) on delete cascade,
  primary key (question_id, theme_slug)
);
create index if not exists question_themes_theme_idx on public.question_themes(theme_slug);

-- 3) Maillage « Pour approfondir → » vers des dossiers (calqué sur dossiers_lies)
create table if not exists public.question_dossiers (
  question_id bigint not null references public.questions(id) on delete cascade,
  dossier_id  bigint not null references public.dossiers(id) on delete cascade,
  ordre       integer not null default 0,
  primary key (question_id, dossier_id)
);

-- 4) RLS : lecture publique du publié (+ admin voit tout) ; écriture admin.
alter table public.questions         enable row level security;
alter table public.question_themes   enable row level security;
alter table public.question_dossiers enable row level security;

drop policy if exists questions_public_read on public.questions;
create policy questions_public_read on public.questions
  for select to public using (publiee or public.is_admin());
drop policy if exists questions_admin_write on public.questions;
create policy questions_admin_write on public.questions
  for all to authenticated using (public.is_admin()) with check (public.is_admin());

drop policy if exists question_themes_public_read on public.question_themes;
create policy question_themes_public_read on public.question_themes for select to public using (true);
drop policy if exists question_themes_admin_write on public.question_themes;
create policy question_themes_admin_write on public.question_themes
  for all to authenticated using (public.is_admin()) with check (public.is_admin());

drop policy if exists question_dossiers_public_read on public.question_dossiers;
create policy question_dossiers_public_read on public.question_dossiers for select to public using (true);
drop policy if exists question_dossiers_admin_write on public.question_dossiers;
create policy question_dossiers_admin_write on public.question_dossiers
  for all to authenticated using (public.is_admin()) with check (public.is_admin());

-- ---- PREUVE : tables créées et vides ------------------------------------
select 'questions' t, count(*) n from public.questions
union all select 'question_themes', count(*) from public.question_themes
union all select 'question_dossiers', count(*) from public.question_dossiers;
